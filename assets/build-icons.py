# Turns the five icons exported from a Figma frame (assets/*.svg) into hooks/strip-icons.ts.
# The paths, gradients and sizes are kept exactly; only the export's backdrop rects go, and every id gets the icon's
# name in front so five icons can sit in one SVG. Run: python assets/build-icons.py
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
out = ["// generated by assets/build-icons.py from a Figma frame: do not edit by hand", "export const ICONS = {"]
for name in ["agent", "weekly", "five", "warm", "cold", "tokens"]: 
    s = open(os.path.join(here, name + ".svg"), encoding="utf8").read()
    w, h = re.search(r'<svg width="([\d.]+)" height="([\d.]+)"', s).groups()
    body = s[s.index(">") + 1 : s.rindex("</svg>")]
    # the export's dark backdrop and the page's white rect
    body = re.sub(r'<rect width="[\d.]+" height="[\d.]+" fill="#1E1E1E"/>\s*', "", body, count=1)
    body = re.sub(r'<rect width="1574" height="802"[^>]*/>\s*', "", body, count=1)
    body = re.sub(r"<title>[^<]*</title>\s*", "", body)
    ids = set(re.findall(r'id="([^"]+)"', body))
    for i in sorted(ids, key=len, reverse=True):
        if re.search(r"url\(#" + re.escape(i) + r"\)", body):
            body = body.replace('id="%s"' % i, 'id="%s-%s"' % (name, i)).replace("url(#%s)" % i, "url(#%s-%s)" % (name, i))
    body = re.sub(r' id="(?!%s-)[^"]*"' % name, "", body)  # layer names: not needed, and not unique across icons
    body = re.sub(r">\s+<", "><", body).strip()
    assert "`" not in body and "${" not in body
    out.append("  %s: { w: %s, h: %s, body: `%s` }," % (name, w, h, body))
out.append("} as const")
open(os.path.join(here, "..", "hooks", "strip-icons.ts"), "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("ok")
